// A furnace, as the game plays it (AbstractFurnaceBlockEntity.serverTick): a block with three slots — input,
// fuel, output — that burns a fuel for its burn time and, while it burns and an input has a smelting recipe,
// cooks it for the recipe's cooking time; the block is lit while it burns. Its menu shows the burn and the
// cooking (ContainerSetData) to whoever has it open.

// furnace is a furnace block's entity.
type furnace struct {
	s         [3]slotItem
	lit       int // ticks of fire left
	litTotal  int // the burn time of the fuel that is burning
	cook      int // cooking progress
	cookTotal int
	facing    string
	told      [4]int // the menu data as it was last sent
}

// fuelTicks are the burn times of the fuels the bot meets: the game's FuelValues, which are code, not data
// (the pack and the extraction do not have them): from the game's code, to be generated by the extractor; an item
// not here is not a fuel in this game.
var fuelTicks = map[string]int{
	"minecraft:coal": 1600, "minecraft:charcoal": 1600, "minecraft:coal_block": 16000, "minecraft:lava_bucket": 20000,
	"minecraft:blaze_rod": 2400, "minecraft:stick": 100, "minecraft:crafting_table": 300, "minecraft:chest": 300,
	"minecraft:wooden_pickaxe": 200, "minecraft:wooden_axe": 200, "minecraft:wooden_shovel": 200, "minecraft:wooden_sword": 200, "minecraft:wooden_hoe": 200,
}

// burnTime is an item's burn time (planks and logs of any wood 300), 0: not a fuel.
func burnTime(item string) int {
	if n, ok := fuelTicks[item]; ok {
		return n
	}
	if strings.HasSuffix(item, "_planks") || strings.HasSuffix(item, "_log") || strings.HasSuffix(item, "_wood") {
		return 300
	}
	return 0
}

// smeltOf is the smelting recipe an item is cooked by (the first in the pack's order).
func smeltOf(item string) (recipe.Recipe, bool) {
	for _, r := range recipe.All() {
		if r.Kind == "minecraft:smelting" && len(r.Ingredients) == 1 && itemMatches(r.Ingredients[0], item) {
			return r, true
		}
	}
	return recipe.Recipe{}, false
}

// mayPlace says whether an item may be put in a slot of the menu: a furnace takes smeltable items in its
// input, fuels in its fuel slot, and nothing in its output.
func (g *Game) mayPlace(m *menu, slot int, item string) bool {
	if !m.furnace {
		return true
	}
	switch slot {
	case 0:
		_, ok := smeltOf(item)
		return ok
	case 1:
		return burnTime(item) > 0
	case 2:
		return false
	}
	return true
}

// facingOf is the way a block placed faces: toward the player (the opposite of where it looks).
func (g *Game) facingOf() string {
	yaw := g.yaw
	for yaw < 0 {
		yaw += 360
	}
	for yaw >= 360 {
		yaw -= 360
	}
	switch {
	case yaw >= 315 || yaw < 45:
		return "north" // looking south
	case yaw < 135:
		return "east" // looking west
	case yaw < 225:
		return "south" // looking north
	}
	return "west"
}

// furnaceState is the furnace block's state for a facing and its fire.
func furnaceState(facing string, lit bool) block.StateID {
	want := fmt.Sprintf("minecraft:furnace[facing=%s,lit=%v]", facing, lit)
	for i := range block.StateList {
		if block.StateList[i].ID() == "minecraft:furnace" && world.StateString(block.StateID(i)) == want {
			return block.StateID(i)
		}
	}
	panic("no state " + want)
}

// placeFurnace puts the furnace item down at x, y, z and starts its entity.
func (g *Game) placeFurnace(x, y, z int) {
	f := &furnace{facing: g.facingOf()}
	if g.furnaces == nil {
		g.furnaces = map[[3]int]*furnace{}
	}
	g.furnaces[[3]int{x, y, z}] = f
	g.S.World.SetState(x, y, z, furnaceState(f.facing, false))
}

// openFurnace opens the furnace at pos: the screen, its contents, its data.
func (g *Game) openFurnace(pos [3]int) error {
	g.containerID = g.containerID%100 + 1
	m := furnaceMenu(g.containerID, pos)
	g.open = m
	idx := slices.Index(registryid.Menu, "minecraft:furnace")
	if err := g.S.Send(play.OpenScreen{ContainerID: pk.VarInt(m.id), Type: pk.VarInt(idx), Title: types.Text(chat.Text("Furnace"))}); err != nil {
		return err
	}
	g.stateID++
	items := make([]types.ItemStack, m.end)
	for i, s := range g.view(m) {
		items[i] = itemStack(s)
	}
	view := g.view(m)
	copy(m.snap[:], view)
	if err := g.S.Send(play.ContainerSetContent{ContainerID: pk.VarInt(m.id), StateID: pk.VarInt(g.stateID), Items: items, CarriedItem: itemStack(g.cursor)}); err != nil {
		return err
	}
	f := g.furnaces[pos]
	f.told = [4]int{-1, -1, -1, -1} // (all the data is sent)
	return g.furnaceData(m, f)
}

// furnaceData tells the open menu the burn and the cooking where they changed.
func (g *Game) furnaceData(m *menu, f *furnace) error {
	now := [4]int{f.lit, f.litTotal, f.cook, f.cookTotal}
	for i, v := range now {
		if f.told[i] != v {
			f.told[i] = v
			if err := g.S.Send(play.ContainerSetData{ContainerID: pk.VarInt(m.id), ID: pk.Short(i), Value: pk.Short(v)}); err != nil {
				return err
			}
		}
	}
	return nil
}

// furnacesTick plays every furnace for a tick, in the order of their places.
func (g *Game) furnacesTick() error {
	var keys [][3]int
	for k := range g.furnaces {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return slices.Compare(keys[i][:], keys[j][:]) < 0 })
	for _, k := range keys {
		f := g.furnaces[k]
		if err := g.furnaceTick(k, f); err != nil {
			return err
		}
	}
	return nil
}

func (f *furnace) canBurn() (recipe.Recipe, bool) {
	if f.s[0].n == 0 {
		return recipe.Recipe{}, false
	}
	r, ok := smeltOf(f.s[0].item)
	if !ok {
		return r, false
	}
	out := f.s[2]
	if out.n == 0 {
		return r, true
	}
	return r, out.item == r.Result && out.n+r.Count <= stackLimit(r.Result)
}

// furnaceTick is AbstractFurnaceBlockEntity.serverTick for one furnace.
func (g *Game) furnaceTick(pos [3]int, f *furnace) error {
	wasLit := f.lit > 0
	if f.lit > 0 {
		f.lit--
	}
	hasFuel, hasInput := f.s[1].n > 0, f.s[0].n > 0
	if f.lit > 0 || hasFuel && hasInput {
		r, can := f.canBurn()
		if f.lit == 0 && can && hasFuel { // a fuel burning
			f.lit = burnTime(f.s[1].item)
			f.litTotal = f.lit
			if f.lit > 0 {
				f.s[1].n--
				if f.s[1].n == 0 {
					f.s[1] = slotItem{}
				}
			}
		}
		if f.lit > 0 && can {
			f.cookTotal = r.Cooking
			if f.cook++; f.cook >= f.cookTotal {
				f.cook = 0
				if f.s[2].n == 0 {
					f.s[2] = slotItem{item: r.Result, n: r.Count}
				} else {
					f.s[2].n += r.Count
				}
				f.s[0].n--
				if f.s[0].n == 0 {
					f.s[0] = slotItem{}
				}
			}
		} else {
			f.cook = 0
		}
	} else if f.lit == 0 && f.cook > 0 {
		f.cook = max(f.cook-2, 0)
	}
	if isLit := f.lit > 0; isLit != wasLit { // the block lit or not
		g.S.World.SetState(pos[0], pos[1], pos[2], furnaceState(f.facing, isLit))
		if err := g.S.Send(play.BlockUpdate{Pos: pk.Position{X: pos[0], Y: pos[1], Z: pos[2]}, BlockState: pk.VarInt(furnaceState(f.facing, isLit))}); err != nil {
			return err
		}
	}
	if m := g.open; m != nil && m.furnace && m.pos == pos {
		return g.furnaceData(m, f)
	}
	return nil
}
